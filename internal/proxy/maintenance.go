// MaintenanceHost is one hostname that should show the maintenance page.
type MaintenanceHost struct {
	ID      string
	Host    string
	Message string
	HTTPS   bool
}

// MaintenanceConfig is the Traefik file provider document plus the nginx
// config the maintenance container serves.
type MaintenanceConfig struct {
	TraefikYAML string
	NginxConf   string
	HTML        string
}

// BuildMaintenanceConfig returns empty strings when no host is valid, which
// means the proxy file and container should be removed.
func BuildMaintenanceConfig(hosts []MaintenanceHost) (MaintenanceConfig, error) {
	type router struct {
		Rule        string   `yaml:"rule"`
		EntryPoints []string `yaml:"entryPoints"`
		Priority    int      `yaml:"priority"`
		Service     string   `yaml:"service"`
		TLS         *struct {
			CertResolver string `yaml:"certResolver"`
		} `yaml:"tls,omitempty"`
	}
	type server struct {
		URL string `yaml:"url"`
	}
	type lb struct {
		Servers []server `yaml:"servers"`
	}
	type svc struct {
		LoadBalancer lb `yaml:"loadBalancer"`
	}
	doc := struct {
		HTTP struct {
			Routers  map[string]router `yaml:"routers,omitempty"`
			Services map[string]svc    `yaml:"services,omitempty"`
		} `yaml:"http"`
	}{}
	doc.HTTP.Routers = map[string]router{}
	var nginx strings.Builder
	nginx.WriteString("server { listen 80 default_server; default_type text/html; return 503 \"<h1>Maintenance</h1>\"; }\n")
	seen := map[string]struct{}{}
	var messages []string
	for _, h := range hosts {
		host := strings.ToLower(strings.TrimSpace(h.Host))
		if !safeProxyHost(host) {
			continue
		}
		if _, ok := seen[host]; ok {
			continue
		}
		seen[host] = struct{}{}
		id := sanitize(h.ID + "-" + host)
		if id == "" {
			id = sanitize(host)
		}
		r := router{
			Rule:        fmt.Sprintf("Host(`%s`)", host),
			EntryPoints: []string{"http", "https"},
			Priority:    100000,
			Service:     "dockfin-maintenance",
		}
		if h.HTTPS && WantAutoHTTPS(host) {
			r.TLS = &struct {
				CertResolver string `yaml:"certResolver"`
			}{CertResolver: "letsencrypt"}
		}
		doc.HTTP.Routers["dockfin-maint-"+id] = r
		msg := strings.TrimSpace(h.Message)
		if msg == "" {
			msg = "This site is temporarily unavailable."
		}
		messages = append(messages, msg)
		nginx.WriteString(fmt.Sprintf("server { listen 80; server_name %s; default_type text/html; return 503 \"%s\"; }\n", host, nginxEscape(maintenanceHTML(msg))))
	}
	if len(doc.HTTP.Routers) == 0 {
		return MaintenanceConfig{}, nil
	}
	doc.HTTP.Services = map[string]svc{
		"dockfin-maintenance": {LoadBalancer: lb{Servers: []server{{URL: "http://dockfin-maintenance:80"}}}},
	}
	raw, err := yaml.Marshal(doc)
	if err != nil {
		return MaintenanceConfig{}, err
	}
	banner := "# Generated by Dockfin. Do not edit.\n"
	page := maintenanceHTML(sharedMessage(messages))
	return MaintenanceConfig{TraefikYAML: banner + string(raw), NginxConf: nginx.String(), HTML: page}, nil
}

func sharedMessage(messages []string) string {
	if len(messages) == 0 {
		return "This site is temporarily unavailable."
	}
	first := messages[0]
	for _, m := range messages[1:] {
		if m != first {
			return "This site is temporarily unavailable."
		}
	}
	return first
}

func maintenanceHTML(message string) string {
	return "<!doctype html><html><head><meta charset=\"utf-8\"><title>Maintenance</title></head><body><h1>Maintenance</h1><p>" + html.EscapeString(message) + "</p></body></html>"
}

func nginxEscape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return s
}

func safeProxyHost(host string) bool {
	if host == "" || len(host) > 253 || strings.Contains(host, "..") {
		return false
	}
	for _, r := range host {
		ok := (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '.' || r == '-'
		if !ok {
			return false
		}
	}
	return strings.Contains(host, ".")
}

// CatchallConfig is Coolify's unknown-host response: a low-priority 503, or a redirect.
type CatchallConfig struct {
	Enabled   bool
	URL       string
	Permanent bool
}

// BuildCatchallYAML returns an empty string when the catch-all is disabled.
func BuildCatchallYAML(cfg CatchallConfig) (string, error) {
	if !cfg.Enabled {
		return "", nil
	}
	target := strings.TrimSpace(cfg.URL)
	if target != "" {
		u, err := url.Parse(target)
		if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
			return "", fmt.Errorf("catch-all URL must be an http(s) address")
		}
		if strings.ContainsAny(target, "\n\r`") {
			return "", fmt.Errorf("catch-all URL is invalid")
		}
	}
	type tls struct {
		CertResolver string `yaml:"certResolver"`
	}
	router := map[string]any{
		"entryPoints": []string{"http", "https"},
		"service":     "dockfin-noop",
		"rule":        "PathPrefix(`/`)",
		"priority":    -1000,
		"tls":         tls{CertResolver: "letsencrypt"},
	}
	services := map[string]any{
		"dockfin-noop": map[string]any{
			"loadBalancer": map[string]any{
				"servers": []any{},
			},
		},
	}
	httpDoc := map[string]any{
		"routers":  map[string]any{"dockfin-catchall": router},
		"services": services,
	}
	if target != "" {
		router["middlewares"] = []string{"dockfin-catchall-redirect"}
		httpDoc["middlewares"] = map[string]any{
			"dockfin-catchall-redirect": map[string]any{
				"redirectRegex": map[string]any{
					"regex":       "(.*)",
					"replacement": target,
					"permanent":   cfg.Permanent,
				},
			},
		}
	}
	raw, err := yaml.Marshal(map[string]any{"http": httpDoc})
	if err != nil {
		return "", err
	}
	return "# Generated by Dockfin. Do not edit.\n" + string(raw), nil
}
