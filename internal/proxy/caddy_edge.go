package proxy

import (
	"fmt"
	"strings"
)

const CaddyDynamicDir = "/data/dockfin/proxy/caddy/dynamic"
const CaddyfilePath = CaddyDynamicDir + "/Caddyfile"

// BuildCaddyfile is the base file caddy-docker-proxy merges with container labels.
// Maintenance sites use a named matcher so they win over the resource handle.
// The catch-all uses the bare :80 and :443 site, which loses to a specific hostname.
func BuildCaddyfile(hosts []MaintenanceHost, catchall CatchallConfig) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by Dockfin. Do not edit.\n")
	seen := map[string]struct{}{}
	for _, h := range hosts {
		host := strings.ToLower(strings.TrimSpace(h.Host))
		if !safeProxyHost(host) {
			continue
		}
		if _, ok := seen[host]; ok {
			continue
		}
		seen[host] = struct{}{}
		site := host
		if !h.HTTPS {
			site = "http://" + host
		}
		fmt.Fprintf(&b, "\n%s {\n", site)
		b.WriteString("\t@dockfin-maintenance path *\n")
		b.WriteString("\thandle @dockfin-maintenance {\n")
		b.WriteString("\t\treverse_proxy " + MaintenanceContainer + ":80 {\n")
		b.WriteString("\t\t\theader_down Retry-After 300\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t}\n")
		b.WriteString("}\n")
	}
	if catchall.Enabled {
		target := strings.TrimSpace(catchall.URL)
		if target != "" {
			if _, err := BuildCatchallYAML(catchall); err != nil {
				return "", err
			}
		}
		b.WriteString("\n:80, :443 {\n")
		if target != "" {
			status := ""
			if catchall.Permanent {
				status = " 301"
			}
			fmt.Fprintf(&b, "\tredir %s%s\n", target, status)
		} else {
			b.WriteString("\treverse_proxy " + MaintenanceContainer + ":80 {\n")
			b.WriteString("\t\thandle_response {\n")
			b.WriteString("\t\t\tcopy_response 503\n")
			b.WriteString("\t\t}\n")
			b.WriteString("\t}\n")
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}
